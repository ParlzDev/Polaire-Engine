// =============================================================================
//  engine/core/console.h —— 控制台能力探测
//
//  两件事：让 Windows 控制台接受 ANSI 转义序列，以及让它按 UTF-8 解释字节。
//  日志模块靠前者决定"要不要输出颜色码"——如果目标不是控制台（输出被重定向到
//  文件或管道），我们就不该把 ESC 字节写进用户的日志文件里。
//
//  后者是本引擎的硬需求而不是锦上添花：日志、断言、示例里的一切中文都是 UTF-8
//  字节，而中文 Windows 的控制台默认跟着系统 ANSI 代码页（936/GBK）。
//  不换代码页，那些字节就会被按 GBK 两两配对，打出来是一堆"璇︽儏"式乱码 ——
//  而乱掉的日志比没有日志更糟：报错就在那一行，人读不出来。
//
//  TODO(M1)：这一层本质是平台调用，等 PAL 建立后整体迁到 platform/win32。
// =============================================================================
#ifndef ENGINE_CORE_CONSOLE_H
#define ENGINE_CORE_CONSOLE_H

#include "engine/core/types.h"

// 尝试启用 ANSI 转义序列处理。
// 返回 true 表示可以安全地输出颜色码。
// 返回 false 表示当前输出目标不支持（重定向、老版本 Windows、非控制台），
// 调用方必须降级为纯文本输出。
//
// 环境里设了 NO_COLOR（非空）时一律返回 false：IDE 的输出面板会把子进程的
// stdout 当纯文本收下来，VT 码就以"[90m"的字面形态显示出来，比乱码更难读，
// 而这种"中间有人捕获"的情形探测不出来，只能给一个显式开关。
bool console_enable_ansi(void);

// 把控制台的输入/输出代码页设为 UTF-8。
// 在 log_init 里调用一次即可：引擎所有文本都是 UTF-8，
// 让终端按别的代码页解释就是自找乱码。
// 返回 false 只可能是"不是控制台"，那种情况下字节流本来就原样写进文件，无需处理。
bool console_set_utf8(void);

#endif // ENGINE_CORE_CONSOLE_H
